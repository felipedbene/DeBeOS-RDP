// The subpixel text-blend half of the Painter oracle: every case in
// tests/text_blend_cases.hpp through app_server's own Painter state and
// PixelFormat subpixel span, printed as tests/text_blend_goldens.inc.
//
// Text is the one caller of the subpixel span that the shape scenes cannot
// reach: AGGTextRenderer hands each LCD glyph scanline to the subpixel
// renderer, whose blend_solid_hspan_subpix is the PixelFormat's
// fBlendSolidHSpanSubpix (agg_renderer_scanline_subpix.h:21-49,
// agg_renderer_region.h). So this drives exactly that call, with the state
// set through Painter's setters in SetDrawState()'s order and the pattern
// forced to B_SOLID_HIGH as SolidPatternGuard does around every string
// (Painter.cpp:1492, :1513). No FreeType runs: the covers are the input.

#include <cstdio>

#include "oracle_prelude.h"

#include "text_blend_cases.hpp"

extern const pattern B_SOLID_HIGH;
extern bool gSubpixelOrderingRGB;

namespace {

rgb_color
to_color(const text_blend_cases::Rgba& c)
{
	rgb_color color;
	color.red = c.r;
	color.green = c.g;
	color.blue = c.b;
	color.alpha = c.a;
	return color;
}

} // namespace

void
print_text_blend_goldens()
{
	using namespace text_blend_cases;
	printf("// Generated by tools/painter_oracle (make painter-goldens) from\n"
		"// app_server's own Painter and PixelFormat subpixel spans. Do not\n"
		"// edit: regenerate. One 0xRRGGBB per case of\n"
		"// tests/text_blend_cases.hpp, in for_each_case() order: the\n"
		"// destination pixel after the glyph pixel is blended.\n");
	int n = 0;
	for_each_case([&](const Case& c) {
		gSubpixelOrderingRGB = c.ordering_rgb;
		uint8 bgra[4] = {c.destination.b, c.destination.g, c.destination.r,
			c.destination.a};
		Painter painter;
		painter.fInternal.fBuffer.attach(bgra, 1, 1, 4);
		painter.fAttached = true;
		// As the scene driver does for AttachToBuffer (Painter.cpp:246-268).
		painter._SetRendererColor(painter.fPatternHandler.HighColor());
		BRegion clip;
		clip.Include(clipping_rect{0, 0, 0, 0});
		painter.ConstrainClipping(&clip);
		// SetDrawState() order, Painter.cpp:305-348.
		painter.SetDrawingMode(static_cast<drawing_mode>(c.mode.mode));
		painter.SetBlendingMode(static_cast<source_alpha>(c.mode.source_alpha),
			static_cast<alpha_function>(c.mode.alpha_function));
		painter.SetHighColor(to_color(c.high));
		painter.SetLowColor(to_color(low));
		// SolidPatternGuard.
		painter.SetPattern(B_SOLID_HIGH);
		painter.fInternal.fPixelFormat.blend_solid_hspan_subpix(0, 0, 3,
			painter.fInternal.fSubpixRenderer.color(), c.covers.c);
		printf("%s0x%02x%02x%02x,", n % 8 == 0 ? (n ? "\n" : "") : " ",
			bgra[2], bgra[1], bgra[0]);
		n++;
	});
	printf("\n");
	gSubpixelOrderingRGB = true;
}
